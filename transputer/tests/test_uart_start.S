/*
 * Minimal assembly-only boot sanity check.
 *
 * Expected: SH
 */

.section .text.start,"ax"
.global _start

_start:
    /* Move workspace above code/data. */
    .byte 0x24, 0x20, 0x20, 0x20, 0xB0

    /* Clear processor error state and initialize queues/timer. */
    .byte 0x22, 0xF9
    .byte 0x25, 0xF7
    .byte 0x24, 0xF2
    .byte 0x21, 0xF8
    .byte 0x24, 0xF2
    .byte 0x21, 0xFC
    .byte 0x40
    .byte 0x25, 0xF4

    /* UART <- 'S' */
    .byte 0x21, 0x20, 0x20, 0x20
    .byte 0x20, 0x20, 0x20, 0x40
    .byte 0x25, 0x43
    .byte 0x20, 0xF0
    .byte 0xE0

    /* UART <- 'H' */
    .byte 0x21, 0x20, 0x20, 0x20
    .byte 0x20, 0x20, 0x20, 0x40
    .byte 0x24, 0x48
    .byte 0x20, 0xF0
    .byte 0xE0

    /* stopp */
    .byte 0x21, 0xF5
