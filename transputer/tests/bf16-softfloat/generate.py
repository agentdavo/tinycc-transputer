#!/usr/bin/env python3
"""Use the supplied RISC-V/default-NaN SoftFloat fork without modifying it."""
import argparse, hashlib, json, random, shutil, subprocess, tempfile
from pathlib import Path
p=argparse.ArgumentParser(); p.add_argument('--source',type=Path,required=True); p.add_argument('--out',type=Path,required=True); p.add_argument('--format',choices=['bf16','f16'],default='bf16'); a=p.parse_args()
a.out.mkdir(parents=True,exist_ok=True)
here=Path(__file__).resolve().parent
files=['bf16_to_f32.c','f32_to_bf16.c','s_roundPackToBF16.c','s_normSubnormalF32Sig.c','softfloat_state.c','softfloat_raiseFlags.c','s_countLeadingZeros8.c']
binary=a.format=='f16'
if binary: files=['f16_to_f32.c','f32_to_f16.c','s_roundPackToF16.c','s_normSubnormalF16Sig.c',*files[3:]]
def widened(x):
    if not binary: return x<<16
    sign=(x&0x8000)<<16; exp=(x>>10)&31; frac=x&1023
    if exp==31: return sign|0x7f800000|(frac<<13)
    if exp: return sign|((exp+112)<<23)|(frac<<13)
    if not frac: return sign
    n=frac.bit_length()
    return sign|((102+n)<<23)|((frac<<(24-n))&0x7fffff)
with tempfile.TemporaryDirectory(prefix='bf16-reference-') as tmp:
    w=Path(tmp)
    for f in a.source.glob('*.h'): shutil.copyfile(f,w/f.name)
    for f in files: shutil.copyfile(a.source/f,w/f)
    digest=hashlib.sha256()
    for f in sorted(w.iterdir()): digest.update(f.name.encode()+b'\0'+f.read_bytes())
    exe=w/'oracle'
    subprocess.run(['gcc','-O2',*(['-DBINARY16'] if binary else []),'-I'+str(w),str(here/'oracle.c'),*[str(w/f) for f in files],'-o',str(exe)],check=True)
    inputs=set()
    # Both signs; every exponent, even and odd retained significands,
    # below/at/above a tie, plus first/last discarded-bit values.
    for sign in [0,0x80000000]:
        for exp in range(256):
            for frac in ([0,1,0x3fe,0x3ff] if binary else [0,1,0x7e,0x7f]):
                for low in ([0,1,0xfff,0x1000,0x1001,0x1fff] if binary else [0,1,0x7fff,0x8000,0x8001,0xffff]):
                    inputs.add(sign|(exp<<23)|(frac<<(13 if binary else 16))|low)
    rng=random.Random(329)
    inputs.update(rng.getrandbits(32) for _ in range(1024))
    inputs=sorted(inputs)
    request=''.join(f'0 {x:x}\n' for x in range(65536))+''.join(f'1 {x:x}\n' for x in inputs)
    answers=[tuple(int(s,16 if i==0 else 10) for i,s in enumerate(line.split())) for line in subprocess.check_output([str(exe)],input=request,text=True).splitlines()]
    assert len(answers)==65536+len(inputs)
    widen=answers[:65536]
    # Prove the compact reference representation against every oracle output.
    for x,(value,flags) in enumerate(widen):
        nan=(x&0x7fff)>(0x7c00 if binary else 0x7f80)
        assert value==(0x7fc00000 if nan else widened(x)), (x,value)
        assert flags==(16 if nan and not x&(0x200 if binary else 0x40) else 0)
    rows=[]
    for x,(value,flags) in zip(inputs,answers[65536:]):
        nan=(x&0x7fffffff)>0x7f800000
        if nan: assert value==(0x7e00 if binary else 0x7fc0)
        target=(((x>>16)&0x8000)|0x7e00|((x&0x7fffff)>>13)) if binary else ((x>>16)|0x40)
        rows.append(dict(input=x,softfloat=value,flags=flags,target=target if nan else value))
    doc=dict(format=a.format,source_sha256=digest.hexdigest(),specialization='supplied root headers: RISC-V/default NaN',rounding='nearest-even',widen_patterns=65536,widen_nan_policy_cases=2046 if binary else 254,widen_sha256=hashlib.sha256(b''.join(v.to_bytes(4,'little')+bytes([f]) for v,f in widen)).hexdigest(),narrow=rows)
    (a.out/'reference.json').write_text(json.dumps(doc,indent=2)+'\n')
    if not binary:
        header='/* Generated by generate.py from SoftFloat; see super-reference.json. */\n'
        header+='static const unsigned bf_inputs[]={'+','.join('0x%08xu'%r['input'] for r in rows)+'};\n'
        header+='static const unsigned short bf_wants[]={'+','.join('0x%04x'%r['target'] for r in rows)+'};\n'
        header+='#define VECTOR_COUNT (sizeof(bf_inputs)/sizeof(bf_inputs[0]))\n#define VECTOR_INPUT(i) bf_inputs[i]\n#define VECTOR_WANT(i) bf_wants[i]\n'
        (a.out/'super-vectors.h').write_text(header)
        (a.out/'super-reference.json').write_text(json.dumps({k:v for k,v in doc.items() if k!='narrow'}|dict(narrow_vectors=len(rows),header_sha256=hashlib.sha256(header.encode()).hexdigest()),indent=2)+'\n')
    # Narrowing is split across images to retain the 256 KiB loader layout.
    for part,start in enumerate(range(0,len(rows),2048)):
        batch=rows[start:start+2048]
        header='struct vector { unsigned input, want; };\nstatic const struct vector vectors[]={\n'
        header+=''.join('{0x%08xu,0x%04xu},\n'%(r['input'],r['target']) for r in batch)+'};\n'
        (a.out/f'vectors-{part}.h').write_text(header)
    print(f'SoftFloat: 65536 widening patterns; {len(rows)} narrowing vectors; {(len(rows)+2047)//2048} image parts')
