def bits(n, mode='near'):
    neg=n<0; a=abs(n)
    if not a: return 0
    e=a.bit_length()-1
    if e<=23: sig=a << (23-e)
    else:
        shift=e-23; sig=a>>shift; rem=a&((1<<shift)-1)
        if mode=='near':
            halfway=1<<(shift-1)
            if rem>halfway or (rem==halfway and sig&1): sig+=1
        elif mode=='down' and neg and rem: sig+=1
        if sig == (1<<24): sig>>=1; e+=1
    return (int(neg)<<31)|((e+127)<<23)|(sig&0x7fffff)
