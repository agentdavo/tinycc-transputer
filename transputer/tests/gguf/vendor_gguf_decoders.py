#!/usr/bin/env python3
"""Vendor llama.cpp's GGUF block structs, codebooks and dequantisers into the
T4 emulator, so TVX decodes every quantisation format byte-identically to
upstream instead of relying on a hand transcription.

Usage: vendor_gguf_decoders.py <path/to/llama.cpp> <out_dir>
Writes  <out_dir>/tvx_gguf_tables.h  and  <out_dir>/tvx_gguf_decode.h
"""
import re, sys, os

llama, out = sys.argv[1], sys.argv[2]
common = open(llama + '/ggml/src/ggml-common.h').read()
quants = open(llama + '/ggml/src/ggml-quants.c').read()

# --- structs + tables -------------------------------------------------
hdr = ['/* GENERATED by transputer/tests/gguf/vendor_gguf_decoders.py.\n'
       ' * Verbatim copy of llama.cpp GGUF block layouts and codebooks.\n'
       ' * DO NOT EDIT - regenerate instead. */\n'
       '#ifndef TVX_GGUF_TABLES_H\n#define TVX_GGUF_TABLES_H\n'
       '#include <stdint.h>\n#include <string.h>\n\n'
       'typedef uint16_t ggml_half;\n'
       'typedef struct { ggml_half x, y; } ggml_half2;\n'
       '#define GGML_EXTENSION\n'
       '#define GGML_COMMON_AGGR_S\n'
       '#define GGML_COMMON_AGGR_U\n'
       '#define QK_K 256\n#define K_SCALE_SIZE 12\n\n']

# block-length constants, copied from ggml-common.h
for cname in ['QK4_0','QK4_1','QK5_0','QK5_1','QK8_0','QK8_1','QK4_NL','IQ3S_N_SCALE','QK_MXFP4']:
    m = re.search(r'^#define\s+' + cname + r'\s+(.+)$', common, re.M)
    if m:
        hdr.append('#define %s %s\n' % (cname, m.group(1).strip()))
    else:
        sys.stderr.write('MISSING CONST %s\n' % cname)
hdr.append('\n')

for name in ['block_q4_0','block_q4_1','block_q5_0','block_q5_1','block_q8_0',
             'block_q2_K','block_q3_K','block_q4_K','block_q5_K','block_q6_K',
             'block_iq2_xxs','block_iq2_xs','block_iq2_s','block_iq3_xxs',
             'block_iq3_s','block_iq1_s','block_iq1_m','block_iq4_nl','block_iq4_xs',
             'block_mxfp4']:
    body_re = r'\{((?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*)\}'
    m = re.search(r'typedef struct\s*(?:GGML_EXTENSION\s*)?' + body_re + r'\s*' + name + r';', common, re.S)
    if not m:
        sys.stderr.write('MISSING STRUCT %s\n' % name); continue
    body = m.group(1)
    # the K-quants use a union for d/dmin; keep it, GGML_EXTENSION is defined away
    hdr.append('typedef struct {%s} %s;\n' % (body, name))
hdr.append('\ntypedef union { ggml_half f16; uint16_t u16; } iq1m_scale_t;\n\n')

for ty, name, n in [('uint8_t','kmask_iq2xs',None),('uint8_t','ksigns_iq2xs',None),
                    ('uint64_t','ksigns64',None),
                    ('uint64_t','iq2xxs_grid',None),('uint64_t','iq2xs_grid',None),
                    ('uint64_t','iq2s_grid',None),('uint32_t','iq3xxs_grid',None),
                    ('uint32_t','iq3s_grid',None),('uint64_t','iq1s_grid',None),
                    ('int8_t','kvalues_iq4nl',None),('int8_t','kvalues_fp4',None)]:
    m = re.search(r'GGML_TABLE_BEGIN\(' + ty + r',\s*' + name + r',\s*([A-Za-z0-9_]+)\)(.*?)GGML_TABLE_END\(\)', common, re.S)
    if not m:
        sys.stderr.write('MISSING TABLE %s\n' % name); continue
    cnt = m.group(1)
    if cnt == 'NGRID_IQ1S': cnt = '2048'
    hdr.append('static const %s %s[%s] = {%s};\n' % (ty, name, cnt, m.group(2)))
hdr.append('\n#define kvalues_mxfp4 kvalues_fp4\n#define IQ1S_DELTA 0.125f\n#define IQ1M_DELTA 0.125f\n')
hdr.append('#endif /* TVX_GGUF_TABLES_H */\n')
open(os.path.join(out, 'tvx_gguf_tables.h'), 'w').write(''.join(hdr))

# --- dequantisers -----------------------------------------------------
FMTS = ['q4_0','q4_1','q5_0','q5_1','q8_0','q2_K','q3_K','q4_K','q5_K','q6_K',
        'iq2_xxs','iq2_xs','iq2_s','iq3_xxs','iq3_s','iq1_s','iq1_m','iq4_nl','iq4_xs',
        'mxfp4']
dec = ['/* GENERATED by transputer/tests/gguf/vendor_gguf_decoders.py.\n'
       ' * Verbatim copies of llama.cpp dequantize_row_* - DO NOT EDIT. */\n'
       '#ifndef TVX_GGUF_DECODE_H\n#define TVX_GGUF_DECODE_H\n\n'
       '#include <math.h>\n#include <assert.h>\n#include "tvx_gguf_tables.h"\n'
       '#include "tvx.h"\n\n'
       '#define GGML_RESTRICT\n'
       '#define GGML_UNUSED(x) (void)(x)\n'
       'static inline float tvx_ggml_h2f(ggml_half h){\n'
       '    return tvx_bits_to_float(tvx_f16_to_f32((uint32_t)h));\n}\n'
       '#define GGML_FP16_TO_FP32(x) tvx_ggml_h2f(x)\n'
       '/* E8M0 -> binary32, halved to match llama.cpp\'s kvalues = 2*E2M1 table */\n'
       'static inline float tvx_ggml_e8m0_half(uint8_t e){\n'
       '    return tvx_bits_to_float(tvx_e8m0_to_f32((uint32_t)e)) * 0.5f;\n}\n'
       '#define GGML_E8M0_TO_FP32_HALF(x) tvx_ggml_e8m0_half(x)\n\n']
# helpers the dequantisers call, copied verbatim from ggml-quants.c
for helper in ['get_scale_min_k4']:
    m = re.search(r'\n(?:static\s+)?(?:inline\s+)?void\s+' + helper + r'\(.*?\n\}\n', quants, re.S)
    if m:
        body = m.group(0).strip()
        if not body.startswith('static'):
            body = 'static ' + body
        dec.append(body + '\n\n')
    else:
        sys.stderr.write('MISSING HELPER %s\n' % helper)

found = []
for f in FMTS:
    m = re.search(r'\nvoid dequantize_row_' + re.escape(f) + r'\(.*?\n\}\n', quants, re.S)
    if not m:
        sys.stderr.write('MISSING DEQUANT %s\n' % f); continue
    dec.append('static ' + m.group(0).strip().replace('void dequantize_row_', 'void tvx_dq_', 1) + '\n\n')
    found.append(f)

# ggml type id -> (decoder, block bytes, elems per block)
IDS = {'q4_0':2,'q4_1':3,'q5_0':6,'q5_1':7,'q8_0':8,'q2_K':10,'q3_K':11,'q4_K':12,
       'q5_K':13,'q6_K':14,'iq2_xxs':16,'iq2_xs':17,'iq3_xxs':18,'iq1_s':19,
       'iq4_nl':20,'iq3_s':21,'iq2_s':22,'iq4_xs':23,'iq1_m':29,'mxfp4':39}
dec.append('/* Decode one block of `fmt` (a ggml type id) into binary32.\n'
           ' * Returns elements decoded, or 0 if the format is unsupported. */\n'
           'static int tvx_gguf_decode_block(int fmt, const void *blk, float *out)\n{\n'
           '    switch (fmt) {\n')
for f in found:
    n = 32 if f in ('q4_0','q4_1','q5_0','q5_1','q8_0','iq4_nl','mxfp4') else 256
    dec.append('    case %d: tvx_dq_%s((const block_%s *)blk, out, %d); return %d;\n'
               % (IDS[f], f, f, n, n))
dec.append('    default: return 0;\n    }\n}\n\n'
           'static int tvx_gguf_block_bytes(int fmt)\n{\n    switch (fmt) {\n')
for f in found:
    dec.append('    case %d: return (int)sizeof(block_%s);\n' % (IDS[f], f))
dec.append('    default: return 0;\n    }\n}\n\n#endif /* TVX_GGUF_DECODE_H */\n')
open(os.path.join(out, 'tvx_gguf_decode.h'), 'w').write(''.join(dec))
sys.stderr.write('vendored %d decoders: %s\n' % (len(found), ' '.join(found)))
