#!/usr/bin/env python3
"""Vendor llama.cpp's integer-activation quantisers (Q8_K and Q8_0) and the
generic integer dot kernels that pair each weight format with its activation
format (ggml's vec_dot_type) into the T4 emulator, so QGEMM's integer path
computes exactly what ggml's generic CPU code computes, instead of relying on
a hand transcription.

Usage: vendor_q8k_kernels.py <path/to/llama.cpp> <out_dir>
Writes  <out_dir>/tvx_q8k.h   (needs tvx_gguf_decode.h from
vendor_gguf_decoders.py for the block structs, codebooks and fp16 helper)
"""
import re, sys, os

llama, out = sys.argv[1], sys.argv[2]
quants = open(llama + '/ggml/src/ggml-quants.c').read()
cpu = open(llama + '/ggml/src/ggml-cpu/quants.c').read()

def func(src, sig, what):
    m = re.search(r'\n' + sig + r'\(.*?\n\}\n', src, re.S)
    if not m:
        sys.exit('MISSING %s' % what)
    return m.group(0).strip()

hdr = ['/* GENERATED by transputer/tests/gguf/vendor_q8k_kernels.py.\n'
       ' * Verbatim copies of llama.cpp quantize_row_q8_K_ref,\n'
       ' * quantize_row_q8_0_ref and the generic ggml_vec_dot_*_q8_K and\n'
       ' * ggml_vec_dot_*_q8_0 kernels - DO NOT EDIT, regenerate instead. */\n'
       '#ifndef TVX_Q8K_H\n#define TVX_Q8K_H\n\n'
       '#include <string.h>\n#include "tvx_gguf_decode.h"\n\n'
       '/* block_q8_K, as declared in ggml-common.h: the activation format that\n'
       ' * every K-quant and i-quant integer dot pairs with. */\n'
       'typedef struct {\n'
       '    float   d;              // delta\n'
       '    int8_t  qs[QK_K];       // quants\n'
       '    int16_t bsums[QK_K/16]; // sum of quants in groups of 16\n'
       '} block_q8_K;\n'
       'typedef char tvx_q8k_size_check[sizeof(block_q8_K) == 292 ? 1 : -1];\n\n'
       '#define GGML_CPU_FP16_TO_FP32(x) GGML_FP16_TO_FP32(x)\n'
       '#define GGML_FP32_TO_FP16(x) \\\n'
       '    ((ggml_half)tvx_f32_to_f16(tvx_float_to_bits(x)))\n'
       '#define UNUSED GGML_UNUSED\n'
       '#ifndef MIN\n#define MIN(a, b) ((a) < (b) ? (a) : (b))\n#endif\n'
       '#ifndef MAX\n#define MAX(a, b) ((a) > (b) ? (a) : (b))\n#endif\n\n'
       '/* ggml type ids of the two activation formats */\n'
       '#define TVX_GGML_Q8_0 8\n#define TVX_GGML_Q8_K 15\n\n']

body = func(quants, r'static inline int nearest_int', 'nearest_int')
hdr.append(body.replace('nearest_int(', 'tvx_nearest_int(', 1) + '\n\n')
for act in ('q8_K', 'q8_0'):
    body = func(quants, r'void quantize_row_%s_ref' % act, 'quantize_row_%s_ref' % act)
    body = body.replace('void quantize_row_%s_ref' % act,
                        'static void tvx_quantize_row_%s' % act, 1)
    hdr.append(body.replace('nearest_int(', 'tvx_nearest_int(') + '\n\n')

# (weight format, ggml type id, activation format = its vec_dot_type)
IDS = [('q2_K', 10, 'q8_K'), ('q3_K', 11, 'q8_K'), ('q4_K', 12, 'q8_K'),
       ('q5_K', 13, 'q8_K'), ('q6_K', 14, 'q8_K'), ('iq2_xxs', 16, 'q8_K'),
       ('iq2_xs', 17, 'q8_K'), ('iq3_xxs', 18, 'q8_K'), ('iq1_s', 19, 'q8_K'),
       ('iq3_s', 21, 'q8_K'), ('iq2_s', 22, 'q8_K'), ('iq4_xs', 23, 'q8_K'),
       ('iq1_m', 29, 'q8_K'),
       ('q4_0', 2, 'q8_0'), ('q5_0', 6, 'q8_0'), ('q8_0', 8, 'q8_0'),
       ('iq4_nl', 20, 'q8_0'), ('mxfp4', 39, 'q8_0')]
for f, _, act in IDS:
    name = 'ggml_vec_dot_%s_%s_generic' % (f, act)
    body = func(cpu, r'void ' + re.escape(name), name)
    body = body.replace('void ' + name, 'static void tvx_vd_%s_%s' % (f, act), 1)
    hdr.append(body + '\n\n')

hdr.append('/* ggml type id of the activation format a weight format pairs with\n'
           ' * (TVX_GGML_Q8_K or TVX_GGML_Q8_0), or 0 if it has no integer kernel. */\n'
           'static int tvx_qint_act_type(int fmt)\n{\n    switch (fmt) {\n')
for f, t, act in IDS:
    hdr.append('    case %d: return %s;\n'
               % (t, 'TVX_GGML_Q8_K' if act == 'q8_K' else 'TVX_GGML_Q8_0'))
hdr.append('    default: return 0;\n    }\n}\n\n')
hdr.append('/* Integer dot of n weights of ggml type `fmt` against n activations in\n'
           ' * its partner format.  Returns 0 if `fmt` has no integer kernel. */\n'
           'static int tvx_qint_vec_dot(int fmt, int n, float *s,\n'
           '                            const void *vx, const void *vy)\n{\n'
           '    switch (fmt) {\n')
for f, t, act in IDS:
    hdr.append('    case %d: tvx_vd_%s_%s(n, s, 0, vx, 0, vy, 0, 1); return 1;\n'
               % (t, f, act))
hdr.append('    default: return 0;\n    }\n}\n\n#endif /* TVX_Q8K_H */\n')
open(os.path.join(out, 'tvx_q8k.h'), 'w').write(''.join(hdr))
sys.stderr.write('vendored quantize_row_q8_K_ref, quantize_row_q8_0_ref and '
                 '%d integer dot kernels\n' % len(IDS))
