/* Host reference for test_tvx_q8k.c: quantise the activations to Q8_K and
 * Q8_0 and run llama.cpp's generic integer dot (vendored in tvx_q8k.h) on the
 * real blocks of gguf_all_formats.inc, each weight format against the
 * activation format llama.cpp pairs it with.
 *
 * Every integer result is first checked against the vendored *dequantisers*:
 * sum(dequant(W)[i] * dequant(act)[i]) in double must agree to 1e-5 of the
 * magnitude, so a kernel that decodes even one sub-block wrongly fails here
 * rather than producing a confident wrong reference.
 *
 * Build: cc -std=gnu11 -ffp-contract=off -I../../t4 -o q8k_ref q8k_ref.c -lm
 * Run:   ./q8k_ref > gguf_q8k_dot.inc            (from this directory) */
#include <stdio.h>
#include <stdint.h>
#include <math.h>
#include "tvx_q8k.h"
#include "gguf_all_formats.inc"

#define NE (256 * QALL_NB)
static float a[NE], v[NE], w[256];
static block_q8_K q8[NE / QK_K], q8b[NE / QK_K];
static block_q8_0 q80[NE / QK8_0];

static uint32_t f2b(float f) { union { float f; uint32_t u; } x; x.f = f; return x.u; }

static uint32_t fnv(const void *p, int n)
{
    const uint8_t *b = p;
    uint32_t h = 2166136261u;
    while (n--) { h ^= *b++; h *= 16777619u; }
    return h;
}

/* activation element i as the integer kernel sees it */
static double act_value(int act, int i)
{
    if (act == TVX_GGML_Q8_K)
        return (double)q8[i / QK_K].d * q8[i / QK_K].qs[i % QK_K];
    return (double)GGML_FP16_TO_FP32(q80[i / QK8_0].d) * q80[i / QK8_0].qs[i % QK8_0];
}

int main(void)
{
    int k, b, i, bad = 0;
    float dot[QALL_N];
    double tol[QALL_N];
    int act[QALL_N];

    /* the same activations test_tvx_allformats.c uses */
    for (i = 0; i < NE; i++)
        a[i] = (float)((i % 31) - 15) * 0.0078125f;
    tvx_quantize_row_q8_K(a, q8, NE);
    tvx_quantize_row_q8_0(a, q80, NE);

    /* a second set that is not exact in bfloat16, fed through bf16 */
    for (i = 0; i < NE; i++)
        v[i] = tvx_bits_to_float(tvx_bf16_to_f32(tvx_f32_to_bf16(
                   f2b((float)((i * 37) % 201 - 100) * 0.013f))));
    tvx_quantize_row_q8_K(v, q8b, NE);

    for (k = 0; k < QALL_N; k++) {
        int fmt = qall_fmt[k], bsz = tvx_gguf_block_bytes(fmt), ne = qall_ne[k];
        double ref = 0.0, mag = 0.0, qerr = 0.0;
        float s = 0.0f;

        act[k] = tvx_qint_act_type(fmt);
        dot[k] = 0.0f;
        tol[k] = 0.0;
        if (!act[k])
            continue;
        tvx_qint_vec_dot(fmt, ne * QALL_NB, &s, qall_blk[k],
                         act[k] == TVX_GGML_Q8_K ? (const void *)q8 : (const void *)q80);
        dot[k] = s;
        for (b = 0; b < QALL_NB; b++) {
            tvx_gguf_decode_block(fmt, qall_blk[k] + b * bsz, w);
            for (i = 0; i < ne; i++) {
                double aq = act_value(act[k], b * ne + i);
                double t = (double)w[i] * aq;
                ref += t;
                mag += fabs(t);
                qerr += fabs((double)w[i]) * fabs(a[b * ne + i] - aq);
            }
        }
        /* |f32 dot - integer dot| can be no more than the activation
           quantisation error weighted by |w|, plus float rounding */
        tol[k] = qerr + 1e-5 * mag + 1e-9;
        fprintf(stderr, "%-8s %s int=%+.9e dequant=%+.9e %s\n", qall_name[k],
                act[k] == TVX_GGML_Q8_K ? "q8_K" : "q8_0", s, ref,
                fabs(s - ref) <= 1e-5 * mag + 1e-12 ? "ok" : "MISMATCH");
        if (!(fabs(s - ref) <= 1e-5 * mag + 1e-12))
            bad = 1;
    }
    if (bad)
        return 1;

    printf("/* GENERATED by q8k_ref.c - expected VQ8K/VQ80 bytes and the\n"
           "   integer-activation QGEMM. */\n");
    printf("#define Q8K_ACT_HASH    0x%08Xu /* VQ8K of the f32 activations */\n",
           fnv(q8, sizeof q8));
    printf("#define Q8K_ACT_HASH_BF 0x%08Xu /* VQ8K of the bf16 activations */\n",
           fnv(q8b, sizeof q8b));
    printf("#define Q80_ACT_HASH    0x%08Xu /* VQ80 of the f32 activations */\n",
           fnv(q80, sizeof q80));
    printf("/* activation format: 15 = Q8_K, 8 = Q8_0, 0 = no integer kernel */\n");
    printf("static const int q8k_act[QALL_N] = {");
    for (k = 0; k < QALL_N; k++)
        printf("%s%d", k ? "," : "", act[k]);
    printf("};\nstatic const int q8k_bsz[QALL_N] = {");
    for (k = 0; k < QALL_N; k++)
        printf("%s%d", k ? "," : "", tvx_gguf_block_bytes(qall_fmt[k]));
    printf("};\n/* integer-activation QGEMM, and the most it may differ from f32 QDOT */\n");
    printf("static const unsigned int q8k_dot[QALL_N] = {\n");
    for (k = 0; k < QALL_N; k++)
        printf("  0x%08Xu%s  /* %s */\n", act[k] ? f2b(dot[k]) : 0u,
               k < QALL_N - 1 ? "," : " ", qall_name[k]);
    printf("};\nstatic const float q8k_tol[QALL_N] = {\n");
    for (k = 0; k < QALL_N; k++)
        printf("  %.9ef%s  /* %s */\n", tol[k], k < QALL_N - 1 ? "," : " ",
               qall_name[k]);
    printf("};\n");
    return 0;
}
