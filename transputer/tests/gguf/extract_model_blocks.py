#!/usr/bin/env python3
"""Pull real blocks of every quantisation format out of one model's GGUF
files, several tensors per format, and emit a C header of raw bytes plus
per-entry metadata for the on-target decode and QDOT tests.

Usage: extract_model_blocks.py <prefix> <nblocks> <ntensors> file.gguf...
       extract_model_blocks.py --list file.gguf...

For each format the files hold, it takes up to <ntensors> tensors spread
evenly over every tensor of that format (across all the files, in order),
and from each tensor <nblocks> consecutive blocks starting at its middle
block.  Arrays and macros are named <prefix>_* / <PREFIX>_*."""
import struct, sys, os
FIX={0:1,1:1,2:2,3:2,4:4,5:4,6:4,7:1,10:8,11:8,12:8}
FMT={0:'<B',1:'<b',2:'<H',3:'<h',4:'<I',5:'<i',6:'<f',7:'<B',10:'<Q',11:'<q',12:'<d'}
# ggml type id -> (name, block bytes, elems/block); same table as
# extract_all_formats.py
T={2:('q4_0',18,32),3:('q4_1',20,32),8:('q8_0',34,32),10:('q2_K',84,256),
   11:('q3_K',110,256),12:('q4_K',144,256),13:('q5_K',176,256),14:('q6_K',210,256),
   16:('iq2_xxs',66,256),17:('iq2_xs',74,256),18:('iq3_xxs',98,256),19:('iq1_s',50,256),
   20:('iq4_nl',18,32),
   21:('iq3_s',110,256),22:('iq2_s',82,256),23:('iq4_xs',136,256),29:('iq1_m',56,256),
   39:('mxfp4',17,32)}

def tensors(path):
    """(file, [(name, dims, type, offset)], data start) of a GGUF file."""
    f=open(path,'rb')
    if f.read(4)!=b'GGUF': sys.exit('%s: not a GGUF file'%path)
    struct.unpack('<I',f.read(4)); nt,=struct.unpack('<Q',f.read(8)); nkv,=struct.unpack('<Q',f.read(8))
    def rs():
        n,=struct.unpack('<Q',f.read(8)); return f.read(n).decode('utf8','replace')
    def sk(t):
        if t==8: rs(); return
        if t==9:
            et,=struct.unpack('<I',f.read(4)); n,=struct.unpack('<Q',f.read(8))
            if et==8:
                for _ in range(n): rs()
            else: f.seek(FIX[et]*n,1)
            return
        f.seek(FIX[t],1)
    align=32
    for _ in range(nkv):
        k=rs(); t,=struct.unpack('<I',f.read(4))
        if k=='general.alignment': align=struct.unpack(FMT[t],f.read(FIX[t]))[0]
        else: sk(t)
    out=[]
    for _ in range(nt):
        nm=rs(); nd,=struct.unpack('<I',f.read(4))
        dims=[struct.unpack('<Q',f.read(8))[0] for _ in range(nd)]
        tt,=struct.unpack('<I',f.read(4)); off,=struct.unpack('<Q',f.read(8))
        out.append((nm,dims,tt,off))
    return f,out,(f.tell()+align-1)//align*align

if sys.argv[1] == '--list':
    for p in sys.argv[2:]:
        f,ts,ds=tensors(p); f.close()
        cnt={}
        for nm,dims,tt,off in ts: cnt[tt]=cnt.get(tt,0)+1
        print(os.path.basename(p)+': '+', '.join('%s x%d'%(T[t][0] if t in T else 'type%d'%t,n)
                                                 for t,n in sorted(cnt.items())))
    sys.exit(0)

prefix, NB, NT, paths = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), sys.argv[4:]
cands={}                                   # type -> [(path, name, dims, off, ds)]
for p in paths:
    f,ts,ds=tensors(p); f.close()
    for nm,dims,tt,off in ts:
        if tt not in T: continue
        n=1
        for d in dims: n*=d
        if n//T[tt][2] >= NB: cands.setdefault(tt,[]).append((p,nm,n,off,ds))
entries=[]                                 # (type, blob, file, tensor, first block)
for tt in sorted(cands):
    c=cands[tt]; name,bsz,ne=T[tt]
    k=min(NT,len(c))
    picks=[c[(i*(len(c)-1))//(k-1)] for i in range(k)] if k>1 else [c[0]]
    for p,nm,n,off,ds in picks:
        nblk=n//ne; first=max(0,min(nblk//2,nblk-NB))
        with open(p,'rb') as f:
            f.seek(ds+off+first*bsz); blob=f.read(NB*bsz)
        if len(blob)!=NB*bsz: sys.exit('%s: short read in %s'%(p,nm))
        entries.append((tt,blob,os.path.basename(p),nm,first))
        sys.stderr.write("%-8s %-36s %-32s block %d\n"%(name,os.path.basename(p)[:36],nm,first))
P=prefix.upper()
print("/* GENERATED by extract_model_blocks.py %s %d %d %s */"
      %(prefix,NB,NT,' '.join(os.path.basename(p) for p in paths)))
print("#define %s_NB %d"%(P,NB))
print("#define %s_N  %d"%(P,len(entries)))
for i,(tt,blob,src,nm,first) in enumerate(entries):
    print("/* %d %s : %s :: %s block %d */"%(i,T[tt][0],src,nm,first))
    print("static const unsigned char %s_b%d[%d] = {"%(prefix,i,len(blob)))
    print(",".join(str(b) for b in blob))
    print("};")
print("static const int %s_fmt[%s_N] = {%s};"%(prefix,P,",".join(str(e[0]) for e in entries)))
print("static const int %s_ne[%s_N] = {%s};"%(prefix,P,",".join(str(T[e[0]][2]) for e in entries)))
print("static const char *const %s_name[%s_N] = {%s};"
      %(prefix,P,",".join('"%s %s"'%(T[e[0]][0],e[3]) for e in entries)))
print("static const unsigned char *const %s_blk[%s_N] = {%s};"
      %(prefix,P,",".join("%s_b%d"%(prefix,i) for i in range(len(entries)))))
