#!/usr/bin/env python3
"""Pull a few real blocks of every quantisation format out of the local GGUF
zoo, and emit a C header of raw bytes + per-format metadata for the on-target
QDOT test.
Usage: extract_all_formats.py <models_dir|file.gguf> <nblocks> [--merge old.inc]
--merge keeps every format already in old.inc verbatim (the zoo it came from
need not still exist) and only pulls formats it lacks from the given models."""
import struct, sys, glob, os, re
FIX={0:1,1:1,2:2,3:2,4:4,5:4,6:4,7:1,10:8,11:8,12:8}
FMT={0:'<B',1:'<b',2:'<H',3:'<h',4:'<I',5:'<i',6:'<f',7:'<B',10:'<Q',11:'<q',12:'<d'}
# ggml type id -> (name, block bytes, elems/block)
T={2:('q4_0',18,32),3:('q4_1',20,32),8:('q8_0',34,32),10:('q2_K',84,256),
   11:('q3_K',110,256),12:('q4_K',144,256),13:('q5_K',176,256),14:('q6_K',210,256),
   16:('iq2_xxs',66,256),17:('iq2_xs',74,256),18:('iq3_xxs',98,256),19:('iq1_s',50,256),
   20:('iq4_nl',18,32),
   21:('iq3_s',110,256),22:('iq2_s',82,256),23:('iq4_xs',136,256),29:('iq1_m',56,256),
   39:('mxfp4',17,32)}
def tensors(path):
    f=open(path,'rb')
    if f.read(4)!=b'GGUF': return None,None,None
    struct.unpack('<I',f.read(4)); nt,=struct.unpack('<Q',f.read(8)); nkv,=struct.unpack('<Q',f.read(8))
    def rs():
        n,=struct.unpack('<Q',f.read(8)); return f.read(n).decode('utf8','replace')
    def sk(t):
        if t==8: rs(); return
        if t==9:
            et,=struct.unpack('<I',f.read(4)); n,=struct.unpack('<Q',f.read(8))
            if et==8:
                for _ in range(n): rs()
            else: f.seek(FIX[et]*n,1)
            return
        f.seek(FIX[t],1)
    align=32
    for _ in range(nkv):
        k=rs(); t,=struct.unpack('<I',f.read(4))
        if k=='general.alignment': align=struct.unpack(FMT[t],f.read(FIX[t]))[0]
        else: sk(t)
    out=[]
    for _ in range(nt):
        nm=rs(); nd,=struct.unpack('<I',f.read(4))
        dims=[struct.unpack('<Q',f.read(8))[0] for _ in range(nd)]
        tt,=struct.unpack('<I',f.read(4)); off,=struct.unpack('<Q',f.read(8))
        out.append((nm,dims,tt,off))
    return f,out,(f.tell()+align-1)//align*align

models, NB = sys.argv[1], int(sys.argv[2])
got={}
if len(sys.argv) > 4 and sys.argv[3] == '--merge':
    old=open(sys.argv[4]).read()
    m=re.search(r'#define QALL_NB (\d+)', old)
    if not m or int(m.group(1)) != NB: sys.exit('merge: %s has a different QALL_NB'%sys.argv[4])
    ids={v[0]:k for k,v in T.items()}
    for name,src,tn,n,body in re.findall(r'/\* (\S+) : (.*?) :: (.*?) \*/\n'
            r'static const unsigned char qall_\1\[(\d+)\] = \{\n([0-9,]*)\n\};', old):
        tt=ids[name]; blob=bytes(int(b) for b in body.split(','))
        if len(blob) != int(n) or len(blob) != NB*T[tt][1]: sys.exit('merge: bad %s'%name)
        got[tt]=(name,T[tt][1],T[tt][2],blob,src,tn)
    sys.stderr.write("kept %d formats from %s\n"%(len(got),sys.argv[4]))
for p in ([models] if models.endswith('.gguf') else sorted(glob.glob(models+'/*.gguf'))):
    if all(k in got for k in T): break
    try: f,ts,ds = tensors(p)
    except Exception: continue
    if ts is None: continue
    for nm,dims,tt,off in ts:
        if tt in T and tt not in got:
            name,bsz,ne = T[tt]
            n=1
            for d in dims: n*=d
            if n < NB*ne: continue
            f.seek(ds+off); blob=f.read(NB*bsz)
            if len(blob)==NB*bsz:
                got[tt]=(name,bsz,ne,blob,os.path.basename(p),nm)
                sys.stderr.write("%-9s from %-46s %s\n"%(name,os.path.basename(p)[:46],nm))
    f.close()
print("/* GENERATED by extract_all_formats.py - real blocks from the local GGUF zoo. */")
print("#define QALL_NB %d"%NB)
print("#define QALL_N  %d"%len(got))
for tt in sorted(got):
    name,bsz,ne,blob,src,tn = got[tt]
    print("/* %s : %s :: %s */"%(name,src,tn))
    print("static const unsigned char qall_%s[%d] = {"%(name,len(blob)))
    print(",".join(str(b) for b in blob))
    print("};")
print("static const int qall_fmt[QALL_N]  = {%s};"%",".join(str(t) for t in sorted(got)))
print("static const int qall_ne[QALL_N]   = {%s};"%",".join(str(got[t][2]) for t in sorted(got)))
print("static const char *qall_name[QALL_N] = {%s};"%",".join('"%s"'%got[t][0] for t in sorted(got)))
print("static const unsigned char *qall_blk[QALL_N] = {%s};"%",".join("qall_"+got[t][0] for t in sorted(got)))
