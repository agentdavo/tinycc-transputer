/* Host reference for qwen38_blocks.inc: decode every block with llama.cpp's
 * vendored decoders (t4/tvx_gguf_decode.h) and print, per entry, a hash of
 * the decoded binary32 bits and the dot against two activation vectors,
 * accumulated in the order QDOT defines (per-block partial sum, then into
 * the total).
 *
 *   cc -O2 -ffp-contract=off -I../../t4 qwen38_ref.c -o qwen38_ref
 *   ./qwen38_ref > qwen38_expected.inc
 *
 * test_gguf_decode_parts.c repeats exactly this arithmetic on every part
 * (FPU and soft-float), and test_tvx_qwen38.c checks QDOT against the dots,
 * so the activation generator and the accumulation order here must match
 * theirs (qwen38_act.h holds the shared part). */
#include <stdio.h>
#include <stdint.h>
#include "tvx_gguf_decode.h"
#include "qwen38_blocks.inc"
#include "qwen38_act.h"
static uint32_t f2b(float f){union{float f;uint32_t u;}v;v.f=f;return v.u;}
static float dec[256]; static float a[256*QW_NB];
int main(void){
    unsigned hash[QW_N], dot[2][QW_N];
    int k,b,i,p;
    for(k=0;k<QW_N;k++){
        int fmt=qw_fmt[k], ne=qw_ne[k], bsz=tvx_gguf_block_bytes(fmt);
        unsigned h=QW_HASH_INIT;
        for(b=0;b<QW_NB;b++){
            tvx_gguf_decode_block(fmt, qw_blk[k]+b*bsz, dec);
            for(i=0;i<ne;i++) h=qw_hash_step(h, f2b(dec[i]));
        }
        hash[k]=h;
        for(p=0;p<2;p++){
            float acc=0.0f;
            qw_act(p, a, ne*QW_NB);
            for(b=0;b<QW_NB;b++){
                float t=0.0f;
                tvx_gguf_decode_block(fmt, qw_blk[k]+b*bsz, dec);
                for(i=0;i<ne;i++) t = t + (float)(dec[i]*a[b*ne+i]);
                acc = acc + t;
            }
            dot[p][k]=f2b(acc);
        }
    }
    printf("/* GENERATED by qwen38_ref.c - expected decode hashes and dots. */\n");
    printf("static const unsigned int qw_hash[QW_N] = {\n");
    for(k=0;k<QW_N;k++) printf("  0x%08Xu,  /* %d %s */\n", hash[k], k, qw_name[k]);
    printf("};\n");
    for(p=0;p<2;p++){
        printf("static const unsigned int qw_dot_%c[QW_N] = {\n", 'a'+p);
        for(k=0;k<QW_N;k++) printf("  0x%08Xu,  /* %d */\n", dot[p][k], k);
        printf("};\n");
    }
    return 0;
}
