/* Host reference: decode every format with llama.cpp's vendored decoders and
 * compute the dot in the order QDOT defines. */
#include <stdio.h>
#include <stdint.h>
#include "tvx_gguf_decode.h"
#include "gguf_all_formats.inc"
static uint32_t f2b(float f){union{float f;uint32_t u;}v;v.f=f;return v.u;}
static float dec[256]; static float a[256*4];
int main(void){
    int k,b,i;
    printf("/* GENERATED by qall_ref.c - expected QDOT results. */\n");
    printf("static const unsigned int qall_dot[QALL_N] = {\n");
    for(k=0;k<QALL_N;k++){
        int fmt=qall_fmt[k], ne=qall_ne[k], bsz=tvx_gguf_block_bytes(fmt);
        float acc=0.0f;
        for(i=0;i<ne*QALL_NB;i++) a[i]=(float)((i%31)-15)*0.0078125f;
        for(b=0;b<QALL_NB;b++){
            float t=0.0f;
            tvx_gguf_decode_block(fmt, qall_blk[k]+b*bsz, dec);
            for(i=0;i<ne;i++) t = t + (float)(dec[i]*a[b*ne+i]);
            acc = acc + t;
        }
        printf("  0x%08Xu%s  /* %-8s fmt=%2d bsz=%3d ne=%3d */\n",
               f2b(acc), k<QALL_N-1?",":" ", qall_name[k], fmt, bsz, ne);
    }
    printf("};\n");
    return 0;
}
