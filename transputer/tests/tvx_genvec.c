/*
 * tvx_genvec.c - generate the expected-value tables baked into test_tvx.c.
 *
 * Values come from tvx_ref.h, the independent spec-derived reference model -
 * NOT from the emulator implementation - so the on-target test is checking
 * hardware behaviour against the specification, not against itself.
 *
 *   cc -O2 -o tvx_genvec tvx_genvec.c -lm && ./tvx_genvec > vectors.inc
 */

#include <stdio.h>
#include <stdint.h>
#include "tvx_ref.h"

/* Inputs chosen to cover: exact grid points, every round-to-nearest-even tie,
 * saturation, both zeros, subnormals, Inf and NaN. */
static const uint32_t vec[] = {
    0x00000000u, 0x80000000u,   /* +0, -0                        */
    0x00000001u, 0x80000001u,   /* smallest subnormals           */
    0x00800000u,                /* smallest normal               */
    0x3E800000u, 0xBE800000u,   /* +-0.25  tie -> 0              */
    0x3F000000u, 0xBF000000u,   /* +-0.5   exact                 */
    0x3F400000u, 0xBF400000u,   /* +-0.75  tie -> 1.0            */
    0x3F800000u, 0xBF800000u,   /* +-1.0   exact                 */
    0x3FA00000u, 0xBFA00000u,   /* +-1.25  tie -> 1.0            */
    0x3FC00000u, 0xBFC00000u,   /* +-1.5   exact                 */
    0x3FE00000u, 0xBFE00000u,   /* +-1.75  tie -> 2.0            */
    0x40000000u, 0xC0000000u,   /* +-2.0   exact                 */
    0x40200000u, 0xC0200000u,   /* +-2.5   tie -> 2.0            */
    0x40400000u, 0xC0400000u,   /* +-3.0   exact                 */
    0x40600000u, 0xC0600000u,   /* +-3.5   tie -> 4.0            */
    0x40800000u, 0xC0800000u,   /* +-4.0   exact                 */
    0x40A00000u, 0xC0A00000u,   /* +-5.0   tie -> 4.0            */
    0x40C00000u, 0xC0C00000u,   /* +-6.0   exact / max           */
    0x40E00000u,                /* 7.0     saturates             */
    0x3F800001u,                /* just above 1.0 (bf16 rounding)*/
    0x3F808000u,                /* bf16 tie -> even              */
    0x3F818000u,                /* bf16 tie -> even (rounds up)  */
    0x7F7FFFFFu, 0xFF7FFFFFu,   /* +-max finite (bf16 -> Inf)    */
    0x7F800000u, 0xFF800000u,   /* +-Inf                         */
    0x7F800001u,                /* signalling NaN                */
    0x7FC00000u,                /* quiet NaN                     */
    0x42F60000u,                /* 123.0                         */
    0x3DCCCCCDu                 /* 0.1                           */
};

int main(void)
{
    size_t i;
    size_t n = sizeof(vec) / sizeof(vec[0]);

    printf("/* Generated by tvx_genvec.c from tvx_ref.h - do not edit. */\n");
    printf("#define TVX_NVEC %u\n", (unsigned)n);

    printf("static const unsigned int tvx_in[TVX_NVEC] = {\n");
    for (i = 0; i < n; i++)
        printf("    0x%08Xu%s\n", vec[i], i + 1 < n ? "," : "");
    printf("};\n");

    printf("static const unsigned int tvx_bf16[TVX_NVEC] = {\n");
    for (i = 0; i < n; i++)
        printf("    0x%08Xu%s\n", ref_f32_to_bf16(vec[i]), i + 1 < n ? "," : "");
    printf("};\n");

    printf("static const unsigned int tvx_mxfp4[TVX_NVEC] = {\n");
    for (i = 0; i < n; i++)
        printf("    0x%08Xu%s\n", ref_f32_to_mxfp4(vec[i]), i + 1 < n ? "," : "");
    printf("};\n");

    printf("static const unsigned int tvx_e8m0of[TVX_NVEC] = {\n");
    for (i = 0; i < n; i++)
        printf("    0x%08Xu%s\n", ref_e8m0_of(vec[i]), i + 1 < n ? "," : "");
    printf("};\n");

    /* all 16 E2M1 codes */
    printf("static const unsigned int tvx_mxfp4_dec[16] = {\n");
    for (i = 0; i < 16; i++)
        printf("    0x%08Xu%s\n", ref_mxfp4_to_f32((uint32_t)i), i + 1 < 16 ? "," : "");
    printf("};\n");

    /* a spread of E8M0 scale bytes including both ends and the NaN code */
    {
        static const unsigned e8[] = { 0, 1, 2, 100, 125, 126, 127, 128,
                                       129, 200, 253, 254, 255 };
        size_t m = sizeof(e8) / sizeof(e8[0]);
        printf("#define TVX_NE8 %u\n", (unsigned)m);
        printf("static const unsigned int tvx_e8_in[TVX_NE8] = {\n");
        for (i = 0; i < m; i++)
            printf("    %uu%s\n", e8[i], i + 1 < m ? "," : "");
        printf("};\n");
        printf("static const unsigned int tvx_e8_dec[TVX_NE8] = {\n");
        for (i = 0; i < m; i++)
            printf("    0x%08Xu%s\n", ref_e8m0_to_f32(e8[i]), i + 1 < m ? "," : "");
        printf("};\n");
    }
    return 0;
}
